"""Контракт exit-кодов CLI (#206).

Стабильный контракт для скриптов и CI: коды не меняются между
релизами, новые команды обязаны им следовать.

- ``EXIT_OK`` (0) — операция выполнена успешно.
- ``EXIT_USAGE`` (1) — ошибка использования: неверные аргументы,
  ошибка валидации параметров, отсутствие аутентификации (401).
- ``EXIT_STATE_CONFLICT`` (2) — конфликт состояния записи (HTTP 409):
  запись уже идёт при ``--start`` либо не активна при ``--stop``.
- ``EXIT_RUNTIME_ERROR`` (3) — ошибка исполнения: API недоступен,
  внутренняя ошибка сервера (5xx), сбой локального фоллбэка.
"""

from __future__ import annotations

EXIT_OK = 0
EXIT_USAGE = 1
EXIT_STATE_CONFLICT = 2
EXIT_RUNTIME_ERROR = 3
